  const ROWS = 7;
  const FALLBACK = GLYPHS[" "];

  /** Bikin 1 baris teks jadi blok ASCII (7 baris string) */
  function renderWord(text, onChar) {
    const chars = text.toUpperCase().split("").map((c) => GLYPHS[c] || FALLBACK);
    const lines = [];
    for (let r = 0; r < ROWS; r++) {
      let row = "";
      chars.forEach((glyph) => {
        row += glyph[r].split("").map((bit) => (bit === "1" ? onChar : " ")).join("");
        row += " "; // spasi antar huruf
      });
      lines.push(row.replace(/\s+$/, "") || " ");
    }
    return lines;
  }

  /** Pecah kalimat panjang jadi beberapa baris berdasarkan batas karakter */
  function wrapText(text, maxChars) {
    const words = text.trim().split(/\s+/);
    const lines = [];
    let cur = "";
    words.forEach((w) => {
      const test = cur ? cur + " " + w : w;
      if (test.length > maxChars && cur) {
        lines.push(cur);
        cur = w;
      } else {
        cur = test;
      }
    });
    if (cur) lines.push(cur);
    return lines;
  }

  /**
   * Render teks lirik jadi ASCII art banner, otomatis word-wrap.
   * @returns {string} siap dipakai sebagai textContent elemen <pre>
   */
  function render(text, maxCharsPerLine = 16, onChar = "#") {
    const subLines = wrapText(text || "", maxCharsPerLine);
    const blocks = subLines.map((line) => renderWord(line, onChar).join("\n"));
    return blocks.join("\n\n"); // baris kosong pemisah antar baris kalimat
  }

  return { render };
